#!/usr/bin/env python3
"""Vendor the new tab's fonts from Fontsource: fonts/*.woff2, their OFL licenses and fonts.css.

    python3 -I tools/vendor-fonts.py

Each npm tarball is checked against the registry's sha512 integrity. Only the latin and
latin-ext subsets of the normal style are kept; other scripts fall back to system fonts.
"""
import base64
import hashlib
import io
import json
import os
import re
import tarfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [
    # package, version, css files with the faces we want, slug for the license file
    ('@fontsource/instrument-serif', '5.3.0', ['400.css'], 'instrument-serif'),
    ('@fontsource-variable/inter', '5.3.0', ['index.css'], 'inter'),
    ('@fontsource/ibm-plex-mono', '5.3.0', ['300.css', '400.css'], 'ibm-plex-mono'),
    ('@fontsource-variable/eb-garamond', '5.3.0', ['index.css'], 'eb-garamond'),
]
FACE = re.compile(r'/\* ([\w-]+) \*/\s*@font-face \{(.*?)\}', re.DOTALL)
SUBSET = re.compile(r'-(latin|latin-ext)-[\w]+-normal$')


def fetch(url):
    with urllib.request.urlopen(url) as response:
        return response.read()


def main():
    out_dir = os.path.join(ROOT, 'fonts')
    os.makedirs(out_dir, exist_ok=True)
    css = ['/* Generated by tools/vendor-fonts.py from Fontsource. Do not edit. */\n']
    for package, version, css_files, slug in FONTS:
        meta = json.loads(fetch(f'https://registry.npmjs.org/{package}/{version}'))
        tgz = fetch(meta['dist']['tarball'])
        integrity = 'sha512-' + base64.b64encode(hashlib.sha512(tgz).digest()).decode()
        if integrity != meta['dist']['integrity']:
            raise SystemExit(f'{package}: integrity mismatch')
        with tarfile.open(fileobj=io.BytesIO(tgz)) as tar:
            read = lambda name: tar.extractfile(f'package/{name}').read()
            with open(os.path.join(out_dir, f'{slug}-LICENSE.txt'), 'wb') as f:
                f.write(read('LICENSE'))
            for css_file in css_files:
                for name, body in FACE.findall(read(css_file).decode()):
                    if not SUBSET.search(name):
                        continue
                    woff2, kind = re.search(r"url\(\./files/([\w.-]+\.woff2)\) format\('([\w-]+)'\)", body).groups()
                    with open(os.path.join(out_dir, woff2), 'wb') as f:
                        f.write(read(f'files/{woff2}'))
                    body = re.sub(r'src:[^;]+;', f"src: url(fonts/{woff2}) format('{kind}');", body)
                    css.append(f'/* {name} */\n@font-face {{{body}}}\n')
        print(f'{package} {version} ({integrity[:20]}...)')
    with open(os.path.join(ROOT, 'fonts.css'), 'w') as f:
        f.write('\n'.join(css))


if __name__ == '__main__':
    main()
