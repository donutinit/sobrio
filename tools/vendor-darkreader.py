#!/usr/bin/env python3
"""Vendor a darkreader release into darkreader.js, unchanged, and proxy.js from it.

    python3 -I tools/vendor-darkreader.py 4.9.133
    python3 -I tools/vendor-darkreader.py --proxy-only

Downloads the npm tarball, checks it against the registry's sha512 integrity and copies
package/darkreader.js byte for byte. Then writes proxy.js: Dark Reader's injectProxy function,
copied from darkreader.js, run as a content script in the page's own world (--proxy-only
regenerates it from the darkreader.js already there).
"""
import base64
import hashlib
import io
import json
import os
import sys
import tarfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def fetch(url):
    with urllib.request.urlopen(url) as response:
        return response.read()


PROXY_HEADER = """\
// Generated by tools/vendor-darkreader.py from darkreader.js: do not edit.
// Dark Reader's CSSOM proxy (its injectProxy, MIT, see THIRD_PARTY_NOTICES.md), run as a content
// script in the page's own world. Dark Reader puts it in as an inline <script>, which Chrome always
// blocks in an extension and Firefox blocks where the page's CSP forbids inline scripts. Without
// it, Dark Reader polls every stylesheet of the page on every frame, for as long as the page is open.
(() => {
"""

PROXY_FOOTER = """
  // Dark Reader announces each start with __darkreader__cleanUp (which also takes out a proxy that
  // was in) and tries its inline script right after. If that did not run, the proxy goes in from
  // here, and its __darkreader__inlineScriptsAllowed tells Dark Reader to stop polling. A stop
  // sends the same event, but then Dark Reader's own sheets are gone, so nothing goes in.
  let ran = false;
  document.addEventListener('__darkreader__inlineScriptsAllowed', () => {
    ran = true;
  });
  document.addEventListener('__darkreader__cleanUp', () => {
    ran = false;
    queueMicrotask(() => {
      if (!ran && document.querySelector('style.darkreader--override')) injectProxy(true, true);
    });
  });
})();
"""


def proxy_source(bundle):
    """injectProxy as darkreader.js has it (4 spaces in), moved to 2 spaces, LF line ends."""
    lines = bundle.decode().replace('\r\n', '\n').split('\n')
    start = next(i for i, line in enumerate(lines) if line.startswith('    function injectProxy('))
    end = next(i for i in range(start, len(lines)) if lines[i] == '    }')
    return '\n'.join(line[2:] if line.startswith('  ') else line for line in lines[start:end + 1]) + '\n'


def write_proxy(bundle):
    with open(os.path.join(ROOT, 'proxy.js'), 'w', newline='\n') as f:
        f.write(PROXY_HEADER + proxy_source(bundle) + PROXY_FOOTER)


def main():
    if sys.argv[1] == '--proxy-only':
        with open(os.path.join(ROOT, 'darkreader.js'), 'rb') as f:
            write_proxy(f.read())
        print('proxy.js written')
        return
    version = sys.argv[1]
    meta = json.loads(fetch(f'https://registry.npmjs.org/darkreader/{version}'))
    tgz = fetch(meta['dist']['tarball'])
    integrity = 'sha512-' + base64.b64encode(hashlib.sha512(tgz).digest()).decode()
    if integrity != meta['dist']['integrity']:
        raise SystemExit(f'integrity mismatch: {integrity}')
    with tarfile.open(fileobj=io.BytesIO(tgz)) as tar:
        bundle = tar.extractfile('package/darkreader.js').read()
    with open(os.path.join(ROOT, 'darkreader.js'), 'wb') as f:
        f.write(bundle)
    write_proxy(bundle)
    print(f'darkreader {version} vendored ({integrity[:20]}...), proxy.js written')


if __name__ == '__main__':
    main()
